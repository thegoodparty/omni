import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { capturedTables } from '@/jobs/changes.registry'

// Writes the Prisma migration that installs db_change_capture() and one
// trigger per table a change handler listens to, for exactly the operations
// some handler on that table listens to (src/jobs/changes.registry.ts). Run it
// after adding or removing a change handler and commit what it writes:
//   npm run migrate:db-change-triggers -w packages/gp-api
// A new migration per run, since an applied one cannot be edited; a run that
// changes nothing writes nothing. A test fails when the triggers the
// migrations install and the registry disagree
// (src/dbChanges/dbChangeTriggers.test.ts).

const MIGRATIONS_DIR = path.join(__dirname, '../prisma/schema/migrations')
const MIGRATION_SUFFIX = '_db_change_triggers'

// The primary key's columns reach the trigger as arguments, so row_key names
// them without a per-table function. RETURN NULL: an AFTER trigger's return
// value is ignored, and nothing here rewrites the row.
const FUNCTION = `CREATE OR REPLACE FUNCTION db_change_capture()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  capture_enabled boolean;
BEGIN
  IF current_setting('app.skip_change_events', true) = 'on' THEN
    RETURN NULL;
  END IF;

  SELECT enabled INTO capture_enabled FROM db_change_config WHERE id = 1;
  IF capture_enabled IS NOT TRUE THEN
    RETURN NULL;
  END IF;

  INSERT INTO db_change (table_name, row_key, op, old_row, new_row)
  VALUES (
    TG_TABLE_NAME,
    (
      SELECT jsonb_object_agg(key, value)
      FROM jsonb_each(
        CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END
      )
      WHERE key = ANY (TG_ARGV)
    ),
    lower(TG_OP),
    CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE to_jsonb(OLD) END,
    CASE WHEN TG_OP = 'DELETE' THEN NULL ELSE to_jsonb(NEW) END
  );

  RETURN NULL;
END;
$$;
`

const triggerSql = (
  table: string,
  operations: string[],
  primaryKey: string[],
): string => {
  const name = `${table}_db_change`
  const events = operations
    .map((operation) => operation.toUpperCase())
    .join(' OR ')
  const args = primaryKey.map((column) => `'${column}'`).join(', ')
  return `DROP TRIGGER IF EXISTS "${name}" ON "${table}";
CREATE TRIGGER "${name}" AFTER ${events} ON "${table}"
  FOR EACH ROW EXECUTE FUNCTION db_change_capture(${args});`
}

// A table whose last handler was removed keeps the trigger it had, which would
// go on writing rows nothing reads. Triggers are named `<table>_db_change` by
// triggerSql above, and only this script creates that name.
const dropRemovedTriggers = (tables: string[]): string => `DO $$
DECLARE
  stale record;
BEGIN
  FOR stale IN
    SELECT c.relname AS tbl, t.tgname AS trg
    FROM pg_trigger t
    JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND NOT t.tgisinternal
      AND t.tgname LIKE '%\\_db\\_change'
      AND c.relname <> ALL (ARRAY[${tables.map((t) => `'${t}'`).join(', ')}])
  LOOP
    EXECUTE format('DROP TRIGGER %I ON %I', stale.trg, stale.tbl);
  END LOOP;
END $$;`

export const dbChangeTriggersSql = (): string => {
  const tables = capturedTables()
  const triggers = tables
    .map(({ table, primaryKey, operations }) =>
      triggerSql(table, operations, primaryKey),
    )
    .join('\n\n')
  const names = tables.map(({ table }) => table)
  return [
    '-- Generated by scripts/dbChangeTriggers.ts. Do not edit.',
    FUNCTION,
    triggers,
    dropRemovedTriggers(names),
    '',
  ].join('\n')
}

const previousMigration = (): string | null => {
  const dirs = readdirSync(MIGRATIONS_DIR)
    .filter((entry) => entry.endsWith(MIGRATION_SUFFIX))
    .sort()
  const latest = dirs.at(-1)
  if (!latest) return null
  return readFileSync(
    path.join(MIGRATIONS_DIR, latest, 'migration.sql'),
    'utf8',
  )
}

const main = (): void => {
  const sql = dbChangeTriggersSql()
  if (sql === previousMigration()) {
    console.log('db_change triggers already match the registry')
    return
  }
  const timestamp = new Date().toISOString().replace(/[-:T]/g, '').slice(0, 14)
  const dir = path.join(MIGRATIONS_DIR, `${timestamp}${MIGRATION_SUFFIX}`)
  mkdirSync(dir, { recursive: true })
  writeFileSync(path.join(dir, 'migration.sql'), sql)
  console.log(`Wrote ${path.relative(process.cwd(), dir)}/migration.sql`)
}

if (require.main === module) main()
