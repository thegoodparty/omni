import { mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { getConstructionPlans, getMigrationPlans } from 'pg-boss'

// Writes the Prisma migration that brings the pgboss schema to the version
// the installed pg-boss expects. Run after installing or upgrading pg-boss:
//   npm run migrate:pg-boss -w packages/gp-api
// pg-boss runs with migrate: false, so a version without its migration fails
// every boot and every useTestService suite.

const SCHEMA = 'pgboss'
const MIGRATIONS_DIR = path.join(__dirname, '../prisma/schema/migrations')
const MIGRATION_DIR_RE = /_pg_boss_v(\d+)$/

const construction = getConstructionPlans(SCHEMA)
const versionMatch = construction.match(
  /INSERT INTO pgboss\.version\(version\) VALUES \('(\d+)'\)/,
)
if (!versionMatch) {
  throw new Error('Could not read the schema version from pg-boss')
}
const target = Number(versionMatch[1])

const installed = readdirSync(MIGRATIONS_DIR)
  .map((dir) => dir.match(MIGRATION_DIR_RE))
  .filter((match): match is RegExpMatchArray => match !== null)
  .map((match) => Number(match[1]))
  .reduce<number | null>(
    (max, version) => (max === null || version > max ? version : max),
    null,
  )

if (installed === target) {
  console.log(`pgboss schema migration already at v${target}`)
  process.exit(0)
}

const sql =
  installed === null ? construction : getMigrationPlans(SCHEMA, installed)
const timestamp = new Date().toISOString().replace(/[-:T]/g, '').slice(0, 14)
const dir = path.join(MIGRATIONS_DIR, `${timestamp}_pg_boss_v${target}`)
mkdirSync(dir)
writeFileSync(
  path.join(dir, 'migration.sql'),
  `-- Generated by scripts/pg-boss-migration.ts. Do not edit.\n${sql}\n`,
)
console.log(`Wrote ${path.relative(process.cwd(), dir)}/migration.sql`)
