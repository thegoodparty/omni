import { parseArgs } from 'node:util'
import { Client } from 'pg'
import { z } from 'zod'
import {
  MIRRORED_TABLES,
  SOURCE_SCHEMA,
} from '../../lambda/dms-zerobus/mirroredTables'

const DATABRICKS_HOST = 'dbc-3d8ca484-79f3.cloud.databricks.com'
const TARGET_SCHEMA = 'goodparty_data_catalog.gp_api_mirror_dms'

type Column = { name: string; type: string; toastable: boolean }

const statementSchema = z.object({
  status: z.object({
    state: z.string(),
    error: z.object({ message: z.string().optional() }).optional(),
  }),
})

const quote = (text: string) => `'${text.replaceAll("'", "''")}'`

const typedValue = (column: Column, image: string): string => {
  const text = `${image}:[${quote(column.name)}]::string`
  const numeric = /^numeric\((\d+),(\d+)\)$/.exec(column.type)
  if (/^(smallint|integer)$/.test(column.type)) return `CAST(${text} AS INT)`
  if (column.type === 'bigint') return `CAST(${text} AS BIGINT)`
  if (column.type === 'real') return `CAST(${text} AS FLOAT)`
  if (column.type === 'double precision') return `CAST(${text} AS DOUBLE)`
  if (numeric && Number(numeric[1]) <= 38) {
    return `CAST(${text} AS DECIMAL(${numeric[1]}, ${numeric[2]}))`
  }
  if (column.type === 'boolean') return `CAST(${text} AS BOOLEAN)`
  if (column.type === 'date') return `CAST(${text} AS DATE)`
  if (/^timestamp(\(\d\))? with time zone$/.test(column.type)) {
    return `CAST(concat(regexp_replace(${text}, '(Z|[+-]00(:?00)?)$', ''), '+00:00') AS TIMESTAMP)`
  }
  if (/^timestamp(\(\d\))? without time zone$/.test(column.type)) {
    return `CAST(${text} AS TIMESTAMP_NTZ)`
  }
  return text
}

const viewSql = (table: string, columns: Column[]): string => {
  const selected = columns.map((column) => {
    const value = typedValue(column, 'row_image')
    const ordering = column.toastable
      ? `CASE WHEN op <> 'update' OR array_contains(image_columns, ${quote(column.name)}) THEN seq END`
      : 'seq'
    return `    max_by(${value}, ${ordering}) AS \`${column.name}\``
  })
  return [
    `-- Generated by generate-views.ts from ${SOURCE_SCHEMA}.${table}. Regenerate after a migration changes its columns.`,
    `CREATE OR REPLACE VIEW ${TARGET_SCHEMA}.${table}`,
    `COMMENT ${quote(`Current state of ${SOURCE_SCHEMA}.${table}: the latest change per primary key in dms_cdc_change, deletes removed. TOASTable columns an update left out are carried from the previous change.`)}`,
    'AS',
    'WITH reload AS (',
    `  SELECT max(reloaded_at) AS reloaded_at FROM ${TARGET_SCHEMA}.dms_cdc_reload WHERE source_table = ${quote(table)}`,
    '),',
    'changes AS (',
    "  SELECT c.pk, c.op, c.seq, c.ingested_at, c.row_image, CASE WHEN c.op = 'update' THEN json_object_keys(c.row_image) END AS image_columns",
    `  FROM ${TARGET_SCHEMA}.dms_cdc_change c CROSS JOIN reload r`,
    `  WHERE c.source_schema = ${quote(SOURCE_SCHEMA)} AND c.source_table = ${quote(table)}`,
    '    AND (r.reloaded_at IS NULL OR c.ingested_at >= r.reloaded_at)',
    '),',
    'latest AS (',
    '  SELECT',
    '    max_by(op, seq) AS _dms_op,',
    '    max(ingested_at) AS _dms_ingested_at,',
    selected.join(',\n'),
    '  FROM changes',
    '  GROUP BY pk',
    ')',
    `SELECT ${columns.map((column) => `\`${column.name}\``).join(', ')}, _dms_ingested_at`,
    'FROM latest',
    "WHERE _dms_op <> 'delete'",
  ].join('\n')
}

const main = async (): Promise<void> => {
  const { values: args } = parseArgs({
    options: {
      table: { type: 'string' },
      apply: { type: 'boolean', default: false },
    },
  })
  const tables = args.table ? [args.table] : Object.keys(MIRRORED_TABLES)
  const connectionString = process.env.POC_REPLICATION_DATABASE_URL
  if (!connectionString) throw new Error('POC_REPLICATION_DATABASE_URL not set')
  const warehouseId = process.env.PEOPLE_DATABRICKS_WAREHOUSE_ID
  const apiKey = process.env.PEOPLE_DATABRICKS_API_KEY
  if (args.apply && (!warehouseId || !apiKey)) {
    throw new Error(
      'PEOPLE_DATABRICKS_WAREHOUSE_ID and PEOPLE_DATABRICKS_API_KEY must be set with --apply',
    )
  }

  const client = new Client({ connectionString })
  await client.connect()
  try {
    for (const table of tables) {
      const pkColumns = MIRRORED_TABLES[table]
      if (!pkColumns) throw new Error(`${table} is not in MIRRORED_TABLES`)
      const regclass = `${SOURCE_SCHEMA}.${table}`
      const { rows: columns } = await client.query<Column>(
        `SELECT a.attname AS name, format_type(a.atttypid, a.atttypmod) AS type,
           a.attstorage <> 'p' AS toastable
         FROM pg_attribute a
         WHERE a.attrelid = to_regclass($1) AND a.attnum > 0 AND NOT a.attisdropped
         ORDER BY a.attnum`,
        [regclass],
      )
      if (columns.length === 0) throw new Error(`No table ${regclass}`)
      const { rows: keys } = await client.query<{ name: string }>(
        `SELECT a.attname AS name
         FROM pg_index i
         JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY (i.indkey)
         WHERE i.indrelid = to_regclass($1) AND i.indisprimary
         ORDER BY array_position(i.indkey, a.attnum)`,
        [regclass],
      )
      const actualKey = keys.map((key) => key.name).join(',')
      if (actualKey !== pkColumns.join(',')) {
        throw new Error(
          `${regclass} primary key is (${actualKey}), MIRRORED_TABLES says (${pkColumns.join(',')})`,
        )
      }
      const sql = viewSql(table, columns)
      console.log(`${sql};`)
      if (!args.apply) continue
      const response = await fetch(
        `https://${DATABRICKS_HOST}/api/2.0/sql/statements`,
        {
          method: 'POST',
          headers: {
            Authorization: `Bearer ${apiKey}`,
            'Content-Type': 'application/json',
          },
          body: JSON.stringify({
            warehouse_id: warehouseId,
            statement: sql,
            wait_timeout: '50s',
            on_wait_timeout: 'CANCEL',
          }),
        },
      )
      if (!response.ok) {
        throw new Error(
          `Databricks HTTP ${response.status}: ${(await response.text()).slice(0, 300)}`,
        )
      }
      const body = statementSchema.parse(await response.json())
      if (body.status.state !== 'SUCCEEDED') {
        throw new Error(
          `${table}: Databricks ${body.status.state}: ${body.status.error?.message ?? ''}`,
        )
      }
      console.error(`applied ${TARGET_SCHEMA}.${table}`)
    }
  } finally {
    await client.end()
  }
}

main().catch((err) => {
  console.error('generate-views failed:', err)
  process.exit(1)
})
